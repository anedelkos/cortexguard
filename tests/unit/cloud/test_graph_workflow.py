# ---------------------------------------------------------------------------
# Interrupt / resume tests (checkpointer required)
# ---------------------------------------------------------------------------
# These tests exercise the actual interrupt() path in route_decision by
# providing a mock LLM that returns needs_human_review=True, which causes
# PlanValidator to return passed=False (llm requested human review).
# The graph then enters the needs_human branch and calls interrupt().


@pytest.mark.asyncio
async def test_graph_interrupts_and_resumes_with_approval() -> None:
    """Graph pauses at needs_human and resumes to plan_ready on operator approval."""
    repo = InMemoryIncidentRepository()
    llm = _make_llm(needs_human_review=True)
    validator = PlanValidator(CapabilityAdapter.load_default())
    graph = build_graph(repo, None, llm, validator, checkpoint_store="memory")
    packet = _make_packet()
    config = {"configurable": {"thread_id": packet.trace_id}}

    await run_planning_workflow(packet, graph, thread_id=packet.trace_id)

    snap = graph.get_state(config)
    next_tasks = snap.next
    assert bool(next_tasks), "Graph should have interrupted at route_decision"

    resume_input: dict[str, Any] = {
        "operator_response": {"approved": True, "outcome": "resolved"},
    }
    final_state = await graph.ainvoke(resume_input, config)

    snap2 = graph.get_state(config)
    assert not snap2.next
    assert final_state.get("decision") == "plan_ready"


