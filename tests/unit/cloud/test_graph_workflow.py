def _make_packet() -> MaydayPacket:
    return MaydayPacket(
        trace_id="trace-001",
        device_id="robot-01",
        timestamp=datetime.now(UTC),
        health=SystemHealth(),
    )


def _canned_plan() -> Plan:
    return Plan(
        plan_id=str(uuid.uuid4()),
        context=GoalContext(
            goal_id=str(uuid.uuid4()),
            user_prompt="Cloud planner safe park",
            intent="Park arm safely pending operator review",
        ),
        plan_type=PlanType.REMEDIATION,
        source=PlanSource.CLOUD_AGENT,
        steps=[
            PlanStep(
                description="Park arm in safe home position",
                action=AgentToolCall(
                    action_name="PLACE_ITEM",
                    arguments={
                        "item_name": "arm",
                        "target_location": "home",
                        "tool_id": "RoboticGripper_A",
                    },
                ),
            )
        ],
    )


def _make_llm(needs_human_review: bool = False) -> MockLLMClient:
    return MockLLMClient(
        fixed_response=PlannerResponse(
            candidate_plan=_canned_plan(),
            confidence=0.9,
            needs_human_review=needs_human_review,
            rationale="Generated by mock for test",
            raw_provider_metadata={},
        )
    )


